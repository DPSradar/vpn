// Current language
let currentLang = localStorage.getItem('language') || 'ru';
if (!translations[currentLang]) {
	currentLang = 'ru';
}

// Toggle dropdown - GLOBAL
window.toggleLanguageDropdown = function(e) {
	if (e) { e.preventDefault(); e.stopPropagation(); }
	const dropdown = document.getElementById('language-dropdown');
	if (dropdown) dropdown.classList.toggle('active');
};

// Close dropdown
function closeLanguageDropdown() {
	const dropdown = document.getElementById('language-dropdown');
	if (dropdown) {
		dropdown.classList.remove('active');
	}
}

// Select language - GLOBAL
window.selectLanguage = function(lang) {
	if (!translations[lang]) {
		console.log('No translations for', lang);
		return;
	}
	
	currentLang = lang;
	localStorage.setItem('language', currentLang);
	applyLanguage(currentLang);
	updateDropdownDisplay(currentLang);
	closeLanguageDropdown();
};

// Apply language to all elements with data-translate attribute
function applyLanguage(lang) {
	const elements = document.querySelectorAll('[data-translate]');
	
	elements.forEach((element) => {
		const key = element.getAttribute('data-translate');
		if (translations[lang] && translations[lang][key]) {
			const translation = translations[lang][key];
			
			// Check if element has HTML children
			if (element.children.length === 0) {
				element.textContent = translation;
			} else {
				const htmlElements = Array.from(element.children);
				element.textContent = '';
				element.appendChild(document.createTextNode(translation));
				htmlElements.forEach(child => {
					element.appendChild(child);
				});
			}
		}
	});
	
	// Update HTML lang attribute
	document.documentElement.lang = lang;
	
	// Update text direction for RTL languages (Arabic)
	const config = languageConfig[lang];
	if (config) {
		document.documentElement.dir = config.dir;
	}
}

// Update dropdown display
function updateDropdownDisplay(lang) {
	const dropdown = document.getElementById('language-dropdown');
	if (!dropdown) return;
	
	const currentText = dropdown.querySelector('.language-dropdown__current');
	const items = dropdown.querySelectorAll('.language-dropdown__item');
	
	// Update current language display
	const config = languageConfig[lang];
	if (currentText && config) {
		currentText.textContent = config.code;
	}
	
	// Update active state in menu
	items.forEach(item => {
		const itemLang = item.getAttribute('data-lang');
		if (itemLang === lang) {
			item.classList.add('active');
		} else {
			item.classList.remove('active');
		}
	});
}

// Initialize on page load
function initLanguageSwitcher() {
	applyLanguage(currentLang);
	updateDropdownDisplay(currentLang);
	
	// Close dropdown when clicking outside
	document.addEventListener('click', function(e) {
		const dropdown = document.getElementById('language-dropdown');
		if (dropdown && !dropdown.contains(e.target)) {
			closeLanguageDropdown();
		}
	});
	
	// Close dropdown on escape key
	document.addEventListener('keydown', function(e) {
		if (e.key === 'Escape') {
			closeLanguageDropdown();
		}
	});
}

